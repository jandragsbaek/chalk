export default Effect.gen(function* () {
  const sql = yield* SqlClient.SqlClient;

  for (const [id, name, category] of MOVEMENTS)
    yield* sql`
      INSERT INTO movements (id, name, category, user_added)
      VALUES (${id}, ${name}, ${category}, 0)
      ON CONFLICT DO NOTHING
    `;
  for (const [key, movementId] of NAME_KEYS)
    yield* sql`DELETE FROM movement_aliases WHERE key = ${key} AND movement_id <> ${movementId}`;
  // One level of variations: only under a core, and only if the movement has none itself.
  for (const [id, variationOf] of [
    ...MOVEMENTS.flatMap(([id, , , variationOf]) =>
      variationOf === null ? [] : [[id, variationOf] as const],
    ),
    ...REPARENT,
  ])
    yield* sql`
      UPDATE movements SET variation_of = ${variationOf}
      WHERE id = ${id} AND variation_of IS NULL
        AND EXISTS (SELECT 1 FROM movements WHERE id = ${variationOf} AND variation_of IS NULL)
        AND NOT EXISTS (SELECT 1 FROM movements WHERE variation_of = ${id})
    `;
  for (const [id, , , , family] of MOVEMENTS)
    if (family !== null)
      yield* sql`
        UPDATE movements SET level_family = ${family} WHERE id = ${id} AND level_family IS NULL
      `;
  for (const [key, alias, movementId] of ALIASES)
    yield* sql`
      INSERT INTO movement_aliases (key, alias, movement_id)
      SELECT ${key}, ${alias}, ${movementId}
      WHERE EXISTS (SELECT 1 FROM movements WHERE id = ${movementId})
        AND NOT EXISTS (SELECT 1 FROM movements WHERE id <> ${movementId} AND lower(name) = lower(${alias}))
      ON CONFLICT DO NOTHING
    `;

  // A part of a session can be a benchmark (Fran, Murph); the id is a slug in @chalk/contracts.
  yield* sql`ALTER TABLE workout_parts ADD COLUMN benchmark_id TEXT`;
  yield* sql`CREATE INDEX workout_parts_benchmark ON workout_parts (benchmark_id)`;
});
